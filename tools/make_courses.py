#!/usr/bin/env python3
"""Generate the two shipped course files.

Neither file is *the* competition course: the organiser's arena layout is still
``[TBD]`` in rulebook v1.0. What ships here is

``course/provisional_sample.json``
    Derived from the official LUS tmux session's "Race" waypoint pane
    (``tmux/one_drone_px4/session.yml``). Those 19 points are a flight path, not
    a gate list -- two of them sit 3.35 m apart *vertically*, which no horizontal
    gate pair can -- so the seven unique centres are used as provisional gates
    and the yaw is only a guess. Purpose: smoke-test the pipeline end to end.

``course/arena_template.json``
    A ring of seven 1 m x 1 m gates inside the rulebook's 5 m x 5 m x 2 m field,
    used to exercise timing and laps at competition scale before the real layout
    is published.

Both are edited as data, not code. Once the organiser publishes the arena (or
teams measure it on site), replace the gate list and bump ``source``.

Run from the project root::

    python3 tools/make_courses.py
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from racing_core.course import Course, Gate  # noqa: E402
from racing_core.geometry import Vec3  # noqa: E402

# --- official LUS "Race" pane, verbatim -------------------------------------
OFFICIAL_RACE_WAYPOINTS: list[tuple[float, float, float]] = [
    (-5.0, 4.5, 4.2),      # start / initial hover
    (-0.90, -1.27, 7.48),
    (9.09, 6.26, 4.08),
    (9.27, -3.46, 4.17),
    (-4.0, -6.25, 7.40),
    (-4.48, -5.94, 4.05),
    (4.45, -0.80, 4.09),
    (-2.65, 6.51, 4.30),
    # gates 1..7 repeat twice more in the original, i.e. three laps
    (-2.5, -6.0, 8.0),     # end-of-run hover target
]
OFFICIAL_SOURCE = (
    "LASER-Robotics/laser_uav_system: tmux/one_drone_px4/session.yml, "
    "window trajectories_6ms, pane 'Race' (19 waypoints, 3 laps)"
)

ARENA_SOURCE = (
    "rulebook v1.0 (20/10/2026) section 3: 5 m x 5 m x 2 m field, seven structures "
    "with a 1 m x 1 m clear opening and a 10 cm border, 1 m x 1 m x 0.5 m takeoff base "
    "in a corner; gate placement is a stand-in (section 5.2 allows the map to change)"
)


def wrap_angle(angle: float) -> float:
    """Fold an angle into (-pi, pi]."""
    return math.atan2(math.sin(angle), math.cos(angle))


def _dump(course: Course, notes: list[str], extra: dict | None = None) -> dict:
    payload = course.to_dict()
    payload["notes"] = notes
    if extra:
        payload.update(extra)
    return payload


def build_provisional() -> tuple[Course, list[str], dict]:
    start = Vec3.from_any(OFFICIAL_RACE_WAYPOINTS[0])
    centres = [Vec3.from_any(point) for point in OFFICIAL_RACE_WAYPOINTS[1:-1]]
    end = Vec3.from_any(OFFICIAL_RACE_WAYPOINTS[-1])

    count = len(centres)
    gates = []
    for index, centre in enumerate(centres):
        previous = centres[index - 1]
        following = centres[(index + 1) % count]
        chord = following - previous
        yaw = wrap_angle(math.atan2(chord.y, chord.x))
        gates.append(
            Gate(
                id=index + 1,
                position=centre,
                yaw=yaw,
                width=1.0,
                height=1.0,
                name=f"gate{index + 1}",
                yaw_source="estimated",
            )
        )

    course = Course(
        name="provisional_sample",
        gates=tuple(gates),
        laps=3,
        start=start,
        takeoff_height=start.z,
        landing=Vec3(end.x, end.y, 4.0),
        source=OFFICIAL_SOURCE,
    )
    notes = [
        "Generated by tools/make_courses.py - do not hand edit.",
        "PROVISIONAL: these are flight-path waypoints reused as gate centres.",
        "Every gate yaw is an estimate (chord through the gate); the detector must refine it.",
        "Gates 4 and 5 are 3.35 m apart vertically and only 0.52 m horizontally: treat them as stacked.",
        "Not the competition arena. Replace once the organiser publishes the layout.",
    ]
    extra = {"official_waypoints": [list(point) for point in OFFICIAL_RACE_WAYPOINTS]}
    return course, notes, extra


def build_arena_template() -> tuple[Course, list[str], dict]:
    """Seven gates on a ring inside a 5 x 5 m field, alternating heights."""
    radius = 1.85
    heights = (1.00, 1.40, 0.90, 1.30, 1.00, 1.45, 1.10)
    gates = []
    for index in range(7):
        # Start at +X and go counter-clockwise.
        angle = 2.0 * math.pi * index / 7.0
        position = Vec3(radius * math.cos(angle), radius * math.sin(angle), heights[index])
        # Fly tangentially: the gate normal is the tangent of the ring.
        yaw = wrap_angle(angle + math.pi / 2.0)
        gates.append(
            Gate(
                id=index + 1,
                position=position,
                yaw=yaw,
                width=1.0,
                height=1.0,
                name=f"gate{index + 1}",
                yaw_source="template",
            )
        )
    course = Course(
        name="arena_template",
        gates=tuple(gates),
        laps=2,
        start=Vec3(0.0, 0.0, 0.5),
        takeoff_height=0.6,
        landing=Vec3(0.0, 0.0, 0.0),
        source=ARENA_SOURCE,
    )
    notes = [
        "Generated by tools/make_courses.py - do not hand edit.",
        "Stand-in layout for the rulebook field (5 m x 5 m x 2 m, seven 1 m x 1 m openings).",
        "width/height here are the CLEAR opening; the 10 cm border sits outside them.",
        "Gate heights keep the whole 1 m opening under the 2 m protected ceiling.",
        "Rulebook 5.2 allows the map/obstacle order to change, so treat this as a stand-in.",
        "Replace with the organiser's layout when it is published.",
    ]
    return course, notes, {}


def write(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}")


def main() -> int:
    failures = 0
    for name, builder in (
        ("provisional_sample", build_provisional),
        ("arena_template", build_arena_template),
    ):
        course, notes, extra = builder()
        problems = course.validate()
        payload = _dump(course, notes, extra)
        write(ROOT / "course" / f"{name}.json", payload)

        print(
            f"  {course.gate_count} gates x {course.laps} laps "
            f"= {len(course.sequence())} passes, "
            f"one lap approx {course.lap_length():.1f} m"
        )
        for problem in problems:
            print(f"  [warn] {problem}")
            failures += 1

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
